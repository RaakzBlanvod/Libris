// =============================================================================
// Форматирование списка авторов книги в строку.
//
// Зачем файл: авторы приходят в разных формах в зависимости от источника:
//  - из нашей БД — массив объектов [{ id, name }],
//  - из поиска/Google — тоже объекты, но иногда поля называются иначе,
//  - изредка — просто массив строк или одна строка.
// Раньше это разворачивалось по-разному в нескольких местах; здесь — единый
// устойчивый разбор всех вариантов.
// =============================================================================

export function formatAuthors(book, fallback = 'Автор не указан') {
  const authors = book?.authors;
  if (!authors) return fallback;

  if (Array.isArray(authors)) {
    if (authors.length === 0) return fallback;
    return authors
      .map((author) =>
        typeof author === 'object'
          ? // у объекта пробуем самые вероятные поля имени по очереди
            author.name || author.author || author.full_name || Object.values(author)[0]
          : author // уже строка
      )
      .join(', ');
  }

  // authors — не массив (например, одна строка)
  return String(authors);
}
