// =============================================================================
// Приводит URL к https.
//
// Зачем: обложки книг приходят от Google Books по http:// (cover_url), а сайт
// открыт по https://. Браузер считает это «Mixed Content» и часто не грузит
// такие картинки. Принудительно меняем схему на https (Google отдаёт обложки и
// по https). Пустой/отсутствующий url возвращаем как '' — чтобы сработал
// фолбэк-плейсхолдер на стороне вызова.
// =============================================================================
export function secureUrl(url) {
  if (!url) return '';
  return url.replace(/^http:\/\//i, 'https://');
}
